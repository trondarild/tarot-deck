#!/usr/bin/env python3
"""Build image-model prompts for the minor cards from their symbolism entries.

For each card in docs/*-minor-symbolism.md, the prompt is: the deck's frame for that
kind of card, the card's Image (pips) or Figure (ranks/courts) paragraph, a suit cue,
and the deck's style suffix, taken from the major-card illustration document so the
two stay in step.

Writes, per deck:
  docs/<deck>-minor-illustration-prompts.md   one paste-ready prompt per card
  tools/batches/<deck>-minor.jsonl            one JSON object per card, for batch generation

Usage: python3 tools/prompts_from_symbolism.py
"""

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Portrait, multiples of 16, close to the 1:1.7 card ratio (see docs/local-img-gen-path.md)
WIDTH, HEIGHT = 768, 1296

DECKS = {
    "zen": {
        "title": "Zen deck",
        "symbolism": "docs/zen-buddhism-minor-symbolism.md",
        "style_from": "docs/zen-buddhism-illustration-descriptions.md",
        "out": "docs/zen-minor-illustration-prompts.md",
        "suits": {
            "ea": ("Earth", "Element Earth: settled ground, stone, the weight of the body; quiet and stable."),
            "wa": ("Water", "Element Water: still or flowing water, mist, a tea bowl or kettle where it fits; soft and yielding."),
            "fi": ("Fire", "Element Fire: a brazier, lamp or incense ember where it fits, taut posture, concentrated effort."),
            "wi": ("Wind", "Element Wind: moving air shown in grass, cloth, smoke or leaves; breath and motion."),
            "vo": ("Void", "Element Void: wide unpainted space, sparse forms, a sense of open sky."),
        },
        # pips sit in the ensō like the Way cards; rank cards in the hanging scroll like the Transmission
        "frame": lambda n: ("Inside a single hand-brushed ink circle (ensō), the scene sits within the circle."
                            if n <= 10 else "A tall hanging-scroll composition."),
        "accent": "The only vermilion is a small square seal in the lower corner.",
    },
    "pessimistic": {
        "title": "Pessimist deck",
        "symbolism": "docs/pessimistic-minor-symbolism.md",
        "style_from": "docs/pessimistic-philosophy-illustration-description.md",
        "out": "docs/pessimistic-minor-illustration-prompts.md",
        "suits": {
            "is": ("Isolation", "Dominant wash: slate grey."),
            "an": ("Anchoring", "Dominant wash: caput mortuum violet-brown."),
            "di": ("Distraction", "Dominant wash: bone ochre."),
            "su": ("Sublimation", "Dominant wash: greyed verdigris."),
        },
        "frame": lambda n: "Within a visible rectangular etching plate mark.",
        "accent": "",
    },
}


def style_suffix(path):
    """The style suffix is the blockquote following 'Style suffix' in the illustration doc."""
    text = (ROOT / path).read_text()
    m = re.search(r"Style suffix[^\n]*\n\n> (.+)", text)
    if not m:
        raise SystemExit(f"no style suffix found in {path}")
    return m.group(1).strip()


def card_ids(deck):
    """Map card titles to ids from the deck's English locale."""
    xml = (ROOT / "data" / "decks" / deck / "locales" / "deck.en.xml").read_text()
    return {t: cid for cid, t in re.findall(r'<card id="([\w-]+)">\s*<title>([^<]+)</title>', xml)}


def plain(text):
    """Drop Markdown italics; image models do not need them."""
    return re.sub(r"\*([^*]+)\*", r"\1", text)


def entries(path):
    """Yield (title, scene) for each card section with an Image or Figure paragraph."""
    for block in re.split(r"(?m)^## ", (ROOT / path).read_text())[1:]:
        title, _, body = block.partition("\n")
        m = re.search(r"(?m)^\*\*(?:Image|Figure)\.\*\* (.+)$", body)
        if m:
            yield title.strip(), plain(m.group(1).strip())


def seed(deck, cid):
    return int(hashlib.sha256(f"{deck}-{cid}".encode()).hexdigest()[:8], 16)


def build(deck, cfg):
    suffix = style_suffix(cfg["style_from"])
    ids = card_ids(deck)
    batch, md = [], [f"# {cfg['title']}: illustration prompts for the minor cards", "",
                     f"Generated by `tools/prompts_from_symbolism.py` from `{cfg['symbolism']}`; rerun it after editing "
                     "that file. Each prompt is paste-ready. The same prompts, with output paths and seeds, are in "
                     f"`tools/batches/{deck}-minor.jsonl`.", ""]
    current_suit = None
    for title, scene in entries(cfg["symbolism"]):
        cid = ids.get(title)
        if cid is None:
            raise SystemExit(f"{deck}: no card titled {title!r} in the locale")
        suit_name, cue = cfg["suits"][cid[:2]]
        n = int(cid[2:])
        parts = [cfg["frame"](n), scene, cue, cfg["accent"], suffix]
        prompt = " ".join(p for p in parts if p)
        if suit_name != current_suit:
            md += [f"## {suit_name}", ""]
            current_suit = suit_name
        md += [f"### {title} (`{cid}`)", "", prompt, ""]
        batch.append({"deck": deck, "id": cid, "title": title,
                      "output": f"assets/img/{deck}/{cid}.jpg",
                      "width": WIDTH, "height": HEIGHT, "seed": seed(deck, cid), "prompt": prompt})
    (ROOT / cfg["out"]).write_text("\n".join(md).rstrip() + "\n")
    out = ROOT / "tools" / "batches" / f"{deck}-minor.jsonl"
    out.parent.mkdir(exist_ok=True)
    out.write_text("".join(json.dumps(b, ensure_ascii=False) + "\n" for b in batch))
    print(f"{deck}: {len(batch)} prompts -> {cfg['out']}, {out.relative_to(ROOT)}")


if __name__ == "__main__":
    for deck, cfg in DECKS.items():
        build(deck, cfg)
